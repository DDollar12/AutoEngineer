@app.route("/payments/webhook", methods=["POST"])
def payment_webhook():
    signature = request.headers.get("x-paystack-signature", "")
    expected_signature = hmac.new(
        PAYSTACK_SECRET_KEY.encode("utf-8"),
        request.get_data(),
        hashlib.sha512,
    ).hexdigest()
    if not PAYSTACK_SECRET_KEY or not hmac.compare_digest(signature, expected_signature):
        abort(401)

    payload = request.get_json(silent=True) or {}
    if payload.get("event") != "charge.success":
        return "ignored", 200
    transaction = payload.get("data", {})
    reference = transaction.get("reference")
    with get_db() as conn:
        payment = conn.execute(
            "SELECT * FROM payments WHERE reference = ?", (reference,)
        ).fetchone()
        if payment and transaction.get("amount") == payment["amount"] * 100:
            conn.execute(
                "UPDATE payments SET status = 'paid' WHERE id = ? AND status = 'pending'",
                (payment["id"],),
            )
            conn.execute(
                "UPDATE service_requests SET status = 'paid' WHERE id = ?",
                (payment["request_id"],),
            )
            conn.commit()
        subscription = conn.execute(
            "SELECT * FROM subscriptions WHERE reference = ?", (reference,)
        ).fetchone()
        if subscription and transaction.get("amount") == subscription["amount"] * 100:
            expires_at = datetime.now(timezone.utc) + timedelta(days=PREMIUM_PLANS[subscription["billing_cycle"]]["days"])
            conn.execute(
                "UPDATE subscriptions SET status = 'active', paid_at = CURRENT_TIMESTAMP, expires_at = ? WHERE id = ? AND status = 'pending'",
                (expires_at.isoformat(), subscription["id"]),
            )
            conn.commit()
    return "ok", 200


