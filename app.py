class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def __enter__(self):
        return self

    def __exit__(self, exception_type, exception_value, traceback):
        if exception_type:
            self.connection.rollback()
        else:
            self.connection.commit()
        self.connection.close()

def execute(self, query, parameters=()):
    stripped_query = query.strip()

    if stripped_query.upper().startswith("PRAGMA TABLE_INFO"):
        table_name = stripped_query.split("(")[1].split(")")[0].strip()

        query = """
            SELECT column_name AS name
            FROM information_schema.columns
            WHERE table_name = %s
            ORDER BY ordinal_position
        """

        return self.connection.execute(query, (table_name,))

    query = query.replace("?", "%s")

    query = query.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )

    if "INSERT OR IGNORE INTO " in query.upper():
        query = query.replace(
            "INSERT OR IGNORE INTO ",
            "INSERT INTO ",
            1
        )
        query = f"{query.rstrip().rstrip(';')} ON CONFLICT DO NOTHING"

    return self.connection.execute(query, parameters)

    def executemany(self, query, parameters):
        query = query.replace("?", "%s")
        query = query.replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        )

        if "INSERT OR IGNORE INTO " in query.upper():
            query = query.replace(
                "INSERT OR IGNORE INTO ",
                "INSERT INTO ",
                1
            )
            query = f"{query.rstrip().rstrip(';')} ON CONFLICT DO NOTHING"

        return self.connection.executemany(query, parameters)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()


